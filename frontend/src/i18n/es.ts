/** Textos con datos variables (números, nombres): se traducen por patrón. */
const THEMES: Record<string, string> = { system: 'sistema', light: 'claro', dark: 'oscuro' };
const PATTERNS: Array<[RegExp, (...m: string[]) => string]> = [
  [/^(\d+)(m|h|d) ago$/, (_, n, u) => `hace ${n} ${({ m: 'min', h: 'h', d: 'd' } as Record<string, string>)[u]}`],
  [/^(\d+) (mins?|hrs?|days?) ago$/, (_, n, u) => `hace ${n} ${u.startsWith('min') ? 'min' : u.startsWith('hr') ? (n === '1' ? 'hora' : 'horas') : (n === '1' ? 'día' : 'días')}`],
  [/^Generating with (.+)\.\.\.$/, (_, m) => `Generando con ${m}...`],
  [/^(\d+) entries$/, (_, n) => `${n} entradas`],
  [/^(.+) backend — (\d+) entries$/, (_, b, n) => `backend ${b} — ${n} entradas`],
  [/^(\d+) stored locally$/, (_, n) => `${n} guardadas localmente`],
  [/^(\d+) steps?$/, (_, n) => `${n} pasos`],
  [/^Theme: (\w+) \(click for (\w+)\)$/, (_, a, b) => `Tema: ${THEMES[a] ?? a} (clic para ${THEMES[b] ?? b})`],
  [/^Hide system panel(.*)$/, (_, r) => `Ocultar panel del sistema${r}`],
  [/^Show system panel(.*)$/, (_, r) => `Mostrar panel del sistema${r}`],
  [/^Deep Research: (on|off)$/, (_, s) => `Investigación profunda: ${s === 'on' ? 'activada' : 'desactivada'}`],
  [/^Notifications (.*)$/, (_, k) => `Notificaciones ${k}`],
  [/^Agent "(.+)" created$/, (_, n) => `Agente «${n}» creado`],
  [/^Agent "(.+)" failed:?(.*)$/, (_, n, r) => `El agente «${n}» ha fallado${r ? ':' + r : ''}`],
  [/^No results found for "(.+)"$/, (_, q) => `No se encontraron resultados para «${q}»`],
  [/^(\d+) (seconds?|minutes?|hours?|days?) ago$/, (_, n, u) => `hace ${n} ${({ second: 'segundo', seconds: 'segundos', minute: 'minuto', minutes: 'minutos', hour: 'hora', hours: 'horas', day: 'día', days: 'días' } as Record<string, string>)[u]}`],
];

function lookup(raw: string): string | undefined {
  const k = norm(raw);
  const hit = ES[k];
  if (hit !== undefined) return hit;
  for (const [re, fn] of PATTERNS) {
    const m = k.match(re);
    if (m) return fn(...m);
  }
  return undefined;
}

/** Atributos visibles que también se traducen. */
const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'] as const;

/** Contenido que nunca se toca: lo que escribe el usuario, código y respuestas del modelo. */
const SKIP_SELECTOR =
  'textarea, input, [contenteditable="true"], code, pre, kbd, .prose, .markdown, [class*="markdown"], [style*="user-bubble"], [data-no-translate]';

const norm = (s: string) => s.replace(/\s+/g, ' ').trim();

function skip(el: Element | null): boolean {
  return !!el && !!el.closest(SKIP_SELECTOR);
}

function translateText(node: Text) {
  const raw = node.nodeValue;
  if (!raw || !/[A-Za-z]/.test(raw)) return;
  const hit = lookup(raw);
  if (hit === undefined || skip(node.parentElement)) return;
  const lead = raw.match(/^\s*/)?.[0] ?? '';
  const trail = raw.match(/\s*$/)?.[0] ?? '';
  const next = lead + hit + trail;
  if (next !== raw) node.nodeValue = next;
}

function translateAttrs(el: Element) {
  if (el.closest('code, pre, [data-no-translate]')) return;
  for (const a of ATTRS) {
    const v = el.getAttribute(a);
    if (!v) continue;
    const hit = lookup(v);
    if (hit !== undefined && hit !== v) el.setAttribute(a, hit);
  }
}

function walk(root: Node) {
  if (root.nodeType === Node.TEXT_NODE) return translateText(root as Text);
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  const el = root as Element;
  translateAttrs(el);
  const tw = document.createTreeWalker(el, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  for (let n = tw.nextNode(); n; n = tw.nextNode()) {
    if (n.nodeType === Node.TEXT_NODE) translateText(n as Text);
    else translateAttrs(n as Element);
  }
}

export function installSpanish() {
  document.documentElement.lang = 'es';
  const start = () => {
    walk(document.body);
    new MutationObserver((muts) => {
      for (const m of muts) {
        if (m.type === 'characterData') translateText(m.target as Text);
        else if (m.type === 'attributes') translateAttrs(m.target as Element);
        else m.addedNodes.forEach(walk);
      }
    }).observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: [...ATTRS],
    });
  };
  if (document.body) start();
  else document.addEventListener('DOMContentLoaded', start, { once: true });
}
